from __future__ import annotations

from datetime import datetime, timezone

from lab.core.models import (
    AdapterInfo,
    ComparisonSet,
    ConfirmationToken,
    CostEstimate,
    Diagnostics,
    ErrorItem,
    GroundTruth,
    GroundTruthPage,
    HumanReview,
    LabDocument,
    MetricResult,
    PageResult,
    RunContext,
    RunResult,
    TextBlock,
    UsageRecord,
    WorkspaceRecord,
)


def test_all_contracts_validate() -> None:
    now = datetime.now(timezone.utc)
    adapter = AdapterInfo(
        adapter_id="text.test",
        task="text",
        label="Test",
        kind="local",
        library="test",
        library_version="1",
        license="MIT",
        model_id=None,
        params={},
        available=True,
        unavailable_reason=None,
        supports_blocks=True,
    )
    page = PageResult(
        page=1,
        text="نص",
        blocks=[TextBlock(order=0, text="نص", bbox=(0, 0, 1, 1))],
        status="ok",
        error=None,
        elapsed_ms=1,
    )
    usage = UsageRecord(
        provider="x",
        model=None,
        engine=None,
        prompt_tokens=None,
        completion_tokens=None,
        pages_billed=None,
        cost_usd=None,
        cost_source="unknown",
        latency_ms=1,
        request_count=1,
        retries=0,
    )
    document = LabDocument(
        doc_id="doc_x",
        display_name="تقرير.pdf",
        kind="pdf",
        sha256="a" * 64,
        size_bytes=1,
        page_count=1,
        page_sizes=[(10, 10)],
        has_text_layer=[True],
        pdf_producer=None,
        pdf_creator=None,
        page_tags={1: ["headings"]},
        uploaded_at=now,
    )
    run = RunResult(
        run_id="run_x",
        doc_id=document.doc_id,
        doc_sha256=document.sha256,
        adapter=adapter,
        variant="raw",
        pages=[page],
        page_mapping="exact",
        started_at=now,
        wall_ms=1,
        cpu_ms=1,
        usage=usage,
        status="ok",
        error=None,
        cache_hit=False,
        environment={},
    )
    gt_page = GroundTruthPage(
        page=1,
        text="نص",
        status="verified",
        seeded_from=None,
        verified_by="tester",
        verified_at=now,
        notes=None,
    )
    values = [
        document,
        ComparisonSet(
            set_id="set_x",
            doc_id="doc_x",
            doc_sha256=document.sha256,
            pages=[1],
            gt_versions={1: 1},
            run_ids=["run_x"],
            page_set_hash="h",
        ),
        ErrorItem(
            run_id="run_x",
            variant="raw",
            page=1,
            index=0,
            op="insert",
            ref="",
            hyp="x",
            ref_context="",
            hyp_context="x",
            ref_offset=0,
            hyp_offset=0,
            categories=["latin"],
        ),
        run,
        GroundTruth(
            doc_id="doc_x",
            doc_sha256=document.sha256,
            task="text",
            pages=[gt_page],
            version=1,
            source="manual",
        ),
        MetricResult(
            run_id="run_x",
            page=1,
            gt_version=1,
            cer=0,
            wer=0,
            cer_no_diacritics=0,
            bow_f1=1,
            num_recall=None,
            num_precision=None,
            ref_chars=2,
            hyp_chars=2,
        ),
        Diagnostics(
            run_id="run_x",
            page=1,
            chars=2,
            arabic_ratio=1,
            latin_ratio=0,
            presentation_forms=0,
            replacement_chars=0,
            cid_tokens=0,
            private_use_chars=0,
            empty=False,
            arabic_ligatures=0,
            digits_arabic_indic=0,
            digits_extended=0,
            digits_ascii=0,
            diacritics_detached=0,
            suspected_reversed_arabic=None,
        ),
        HumanReview(
            run_id="run_x",
            page=1,
            rating="correct",
            issues=[],
            notes=None,
            reviewer=None,
            created_at=now,
        ),
        WorkspaceRecord(workspace_id="ws_x", created_at=now, updated_at=now),
        CostEstimate(cost_usd=0),
        RunContext(workspace_id="ws_x"),
        ConfirmationToken(
            doc_sha256=document.sha256,
            pages=[1],
            adapter_id="text.api",
            engine=None,
            model=None,
            estimate_usd=0,
            created_at=now,
        ),
    ]
    assert all(value.schema_version == 1 for value in values)
